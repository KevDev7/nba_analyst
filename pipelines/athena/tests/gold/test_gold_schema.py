def test_gold_tables_expose_expected_column_order(athena_client, athena_settings, table_name: str):
    _, rows = athena_client.execute(
        f"""
        SELECT column_name
        FROM information_schema.columns
        WHERE table_schema = '{athena_settings.database}'
          AND table_name = '{table_name}'
        ORDER BY ordinal_position
        """
    )
    actual_columns = [row["column_name"] for row in rows]
    assert actual_columns == EXPECTED_COLUMN_ORDER[table_name]
